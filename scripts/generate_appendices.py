"""Generate compact whole-file appendices and source hashes; no truncation."""
import hashlib
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STAGES = ['M0', 'M1', 'M2', 'M3_1', 'M3_2']
CODE_SUFFIXES = {'.py', '.sh', '.ps1', '.bat', '.cmd'}

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def discover():
    excluded = {'third_party', '.venv', '__pycache__', '.git', 'deliverables', 'data', 'results', 'agent_logs'}
    sources = []
    for base, dirs, names in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in excluded)
        sources.extend(Path(base) / n for n in sorted(names) if Path(n).suffix in CODE_SUFFIXES)
    sources = sorted(sources)
    sources += sorted(p for p in (ROOT / 'configs').rglob('*') if p.is_file() and '__pycache__' not in p.parts)
    electronic = sorted(p for p in (ROOT / 'reports').rglob('*') if p.is_file()
                        and p.suffix in {'.tex', '.bib'} and 'appendices' not in p.relative_to(ROOT / 'reports').parts)
    return sources, electronic

def main():
    sources, electronic = discover()
    workflows = [ROOT / 'SKILL.md', ROOT / 'AGENT_WORKFLOW.md']
    records, missing = [], []
    lines = ['% Generated by scripts/generate_appendices.py. Whole files only.',
             '\\section{完整自编代码及配置}',
             '以下按文件完整导入；论文正文、方法图和参考文献源文件在附录D列出并随电子附件提供。']
    for p in sources:
        relative = p.relative_to(ROOT).as_posix()
        lines += ['\\subsection*{\\texttt{\\detokenize{' + relative + '}}}', '\\appendixfile{../' + relative + '}']
    lines.append('\\section{主要Codex任务与最终回答}')
    for stage in STAGES:
        lines.append('\\subsection*{' + stage.replace('_', '.') + '}')
        for filename, title in [('prompt.md', 'Prompt'), ('response.md', 'Response')]:
            p = ROOT / 'agent_logs' / stage / filename
            if p.is_file():
                records.append(p)
                lines += ['\\paragraph*{' + title + '}', '\\appendixtext{../' + p.relative_to(ROOT).as_posix() + '}']
            else:
                missing.append(p.relative_to(ROOT).as_posix())
                lines.append('该项真实原文缺失，未编造或补写。')
    lines.append('\\section{项目Skill与Agent工作流}')
    for p in workflows:
        relative = p.relative_to(ROOT).as_posix()
        lines += ['\\subsection*{\\texttt{\\detokenize{' + relative + '}}}', '\\appendixtext{../' + relative + '}']
    lines += ['\\section{第三方源码、数据与电子材料索引}',
              '官方仓库为\\url{https://github.com/THUDM/GraphMAE}，保留MIT许可证。',
              '正式PyG版本Commit：\\par\\noindent\\texttt{9127f25e01aa5ba1cca68b746284aeb7ab2b4850}。',
              'DGL审计版本Commit：\\par\\noindent\\texttt{b14f080c919257b495e3cb6474286d5252d6a635}。',
              '两个完整源码目录和Git bundle电子提供，不重复打印原作者源码。',
              '\\begin{itemize}',
              '\\item 数据：\\texttt{data/cora/}，8个raw与3个processed文件，预处理见实验环境章节。',
              '\\item 实验：\\texttt{results/raw/M0/}、\\texttt{M1/}、\\texttt{M2/}及\\texttt{results/processed/}，含真实日志、配置、预测、必要权重与汇总。',
              '\\item 图片：\\texttt{figures/M1/}、\\texttt{figures/M2/}和\\texttt{reports/figures/}，字体二进制不打包；已渲染图片可直接编译。',
              '\\item 第三方逐文件清单：\\texttt{results/raw/M0/pyg\\_tree.txt}与\\texttt{main\\_tree.txt}。',
              '\\item 依赖：\\texttt{configs/requirements.lock.txt}；项目历史管理文档电子保留。',
              '\\item 全包校验：ZIP内\\texttt{FILE\\_MANIFEST.json}与\\texttt{SHA256SUMS.txt}；根目录\\texttt{BUILD\\_ON\\_WINDOWS.md}说明本地编译。',
              '\\end{itemize}',
              '以下论文及方法图源码电子完整提供，避免重复打印已呈现的正文：',
              '\\begin{itemize}']
    for p in electronic:
        lines.append('\\item \\texttt{\\detokenize{' + p.relative_to(ROOT).as_posix() + '}}')
    lines.append('\\end{itemize}')
    output = ROOT / 'reports/appendices/generated.tex'
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    material = sources + records + workflows + electronic
    manifest = {'sources': [p.relative_to(ROOT).as_posix() for p in sources],
                'records': [p.relative_to(ROOT).as_posix() for p in records],
                'workflows': [p.relative_to(ROOT).as_posix() for p in workflows],
                'electronic_report_sources': [p.relative_to(ROOT).as_posix() for p in electronic],
                'sha256': {p.relative_to(ROOT).as_posix(): sha(p) for p in material},
                'pending_real_records': missing, 'generated_appendix': output.relative_to(ROOT).as_posix(),
                'generated_sha256': sha(output),
                'policy': 'Whole first-party code/config printed; five real task/final pairs; only Skill/workflow printed; report source and third-party complete electronically; no recursive generated.tex import.'}
    (ROOT / 'reports/appendices/manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    docs = ['# 附录与电子材料清单', '', 'M3.3生成：A完整代码配置，B主要真实对话，C两份规范，D简洁电子索引。', '', '| 路径 | 处理 |', '|---|---|']
    for p in sources + records + workflows:
        docs.append('| ' + p.relative_to(ROOT).as_posix() + ' | 全文件自动打印且电子提供 |')
    for p in electronic:
        docs.append('| ' + p.relative_to(ROOT).as_posix() + ' | 电子完整提供，打印列目录 |')
    docs += ['', '第三方源码、MIT许可证、Git bundle、Cora、全部M0/M1/M2原始与汇总证据均电子提供；不含venv、pycache、字体二进制和commentary导出。',
             'M3.3本次最终回答未产生，不预写。PDF须用户本地XeLaTeX编译，当前不声称PDF交付。']
    (ROOT / 'docs/APPENDIX_MANIFEST.md').write_text('\n'.join(docs) + '\n', encoding='utf-8')
    print(json.dumps({'code_config_files': len(sources), 'real_record_files': len(records), 'workflows': len(workflows), 'electronic_tex_bib_files': len(electronic), 'missing': missing}, ensure_ascii=False))

if __name__ == '__main__':
    main()
